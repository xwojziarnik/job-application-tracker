"""Declarative base and mixins shared by all models.

Models list the mixins before ``Base``, e.g.
``class Company(UUIDPrimaryKeyMixin, TimestampMixin, Base)``. In the table, the model's own
columns come first and the mixins' columns after them.
"""

from datetime import datetime
from typing import Any, ClassVar
from uuid import UUID, uuid4

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint names, so Alembic autogenerate produces stable migrations.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Base class of all models; its metadata names constraints by ``NAMING_CONVENTION``."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class TimestampMixin:
    """``created_at`` and ``updated_at`` columns, set by the database (UTC, D-11).

    ``eager_defaults`` makes SQLAlchemy load the values the database sets with
    ``RETURNING``, also after an ``UPDATE``; otherwise ``updated_at`` would be expired and
    reading it would trigger a lazy load, which fails in async code (``MissingGreenlet``).
    """

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )
    __mapper_args__: ClassVar[dict[str, Any]] = {"eager_defaults": True}


class UUIDPrimaryKeyMixin:
    """A UUID v4 primary key named ``id`` (D-01).

    The ID is generated by the application when the row is inserted, so it is ``None``
    until the session is flushed; code that needs it earlier sets ``id`` explicitly.
    Changing the UUID version for all models means changing only this default.
    """

    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
